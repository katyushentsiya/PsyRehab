function ServiceDetailsPage({ initialScrollTo, onGoBack }) {
  const serviceRefs = useRef({});

  useEffect(() => {
    if (initialScrollTo && serviceRefs.current[initialScrollTo]) {
      serviceRefs.current[initialScrollTo].scrollIntoView({ behavior: 'smooth', block: 'start' });
    }
  }, [initialScrollTo]);

  return (
    <div className="service-details-page">
      {Object.values(servicesData).map((service) => (
        <section key={service.id} id={service.id} ref={(el) => (serviceRefs.current[service.id] = el)} className="service-sections">
          <h2 className="service-titles">{service.title}</h2>
          <div className="service-contents">{service.fullDescription}</div>
        </section>
      ))}
    </div>
  );
}

export default ServiceDetailsPage;